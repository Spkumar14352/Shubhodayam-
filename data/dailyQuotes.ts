export function getDailyQuote(dayOfYear?: number): DailyQuote {
  const day = dayOfYear ?? Math.floor((Date.now() - new Date(new Date().getFullYear(), 0, 0).getTime()) / 86400000);
  const index = Math.abs(day) % dailyQuotes.length;
  return dailyQuotes[index];
}
